ERRORS: list[str] = []


def wait_for(cdp: CDP, expression: str, what: str, timeout: float = 6.0) -> None:
    end = time.time() + timeout
    while time.time() < end:
        if cdp.evaluate(expression):
            return
        time.sleep(0.05)
    raise AssertionError(f"timed out waiting for: {what}")


def wait_ready(cdp: CDP) -> None:
    for _ in range(80):
        if cdp.evaluate("document.readyState") == "complete":
            cdp.evaluate("document.fonts ? document.fonts.ready.then(() => true) : Promise.resolve(true)", True)
            time.sleep(0.15)
            return
        time.sleep(0.1)
    raise TimeoutError("page did not reach readyState complete")


def navigate(cdp: CDP, url: str, width: int) -> None:
    # Each navigation resets the in-page error log, so bank it first.
    ERRORS.extend(cdp.evaluate("window.__consoleErrors || []") or [])
    cdp.call("Emulation.setDeviceMetricsOverride", {
        "width": width, "height": 900, "deviceScaleFactor": 1, "mobile": width < 768,
    })
    cdp.call("Page.navigate", {"url": url})
    wait_ready(cdp)
    wait_for(cdp, "!!document.getElementById('kybForm')", "form present")


def lookup(cdp: CDP, value: str) -> None:
    cdp.evaluate(
        "(() => { const i = document.getElementById('kybNumber'); i.value = %s;"
        " document.getElementById('kybForm').requestSubmit(); return true; })()" % json.dumps(value)
    )


def results_ready(cdp: CDP) -> None:
    wait_for(cdp, "!document.getElementById('kybResultsWrap').hidden", "results visible")


def show(cdp: CDP, alias: str) -> None:
    lookup(cdp, alias)
    results_ready(cdp)


def error_text(cdp: CDP) -> str:
    wait_for(cdp, "!document.getElementById('kybError').hidden", "error visible")
    return cdp.evaluate("document.getElementById('kybError').textContent")


def texts(cdp: CDP, selector: str) -> list[str]:
    return cdp.evaluate("[...document.querySelectorAll(%s)].map(n => n.textContent)" % json.dumps(selector))


def section_text(cdp: CDP, heading_id: str) -> str:
    return cdp.evaluate("(document.getElementById(%s) || {parentElement: {textContent: ''}}).parentElement.textContent" % json.dumps(heading_id))


def no_overflow(cdp: CDP, label: str) -> None:
    over = cdp.evaluate("document.documentElement.scrollWidth - window.innerWidth")
    require(over <= 0, f"{label}: horizontal overflow of {over}px")


def hide_banner(cdp: CDP) -> None:
    cdp.evaluate("(() => { const b = document.getElementById('cookieBanner'); if (b) b.style.display = 'none'; return true; })()")


def screenshot(cdp: CDP, name: str, full: bool = False) -> None:
    directory = os.environ.get("KYB_SCREENSHOT_DIR")
    if not directory:
        return
    import base64
    hide_banner(cdp)
    params: dict[str, Any] = {"format": "png"}
    if full:
        size = cdp.evaluate("({w: document.documentElement.clientWidth, h: document.documentElement.scrollHeight})")
        params.update({"captureBeyondViewport": True,
                       "clip": {"x": 0, "y": 0, "width": size["w"], "height": min(size["h"], 6000), "scale": 1}})
    data = cdp.call("Page.captureScreenshot", params)["data"]
    Path(directory).mkdir(parents=True, exist_ok=True)
    (Path(directory) / name).write_bytes(base64.b64decode(data))


def records(body: dict[str, Any]) -> list[dict[str, Any]]:
    """IDV carrying records in render order: officers (first page), then PSC records."""
    return body["officers"]["items"][:20] + body["pscs"]["items"][:20]


def contract_checks(cdp: CDP, alias: str, name: str) -> None:
    """Rendered text equals the API strings exactly for one response."""
    body = MOCKS[alias]["body"]
    show(cdp, alias)
    recs = records(body)
    ivs = [r["identity_verification"] for r in recs]
    require(texts(cdp, ".kyb-idv-display") == [iv["display"] for iv in ivs], f"{name}: IDV display text is not verbatim")
    require(texts(cdp, ".kyb-idv-dne") == [iv["does_not_establish"] for iv in ivs],
            f"{name}: per-record does_not_establish is not verbatim")
    pairs = cdp.evaluate("[...document.querySelectorAll('.kyb-idv-state')].map(dl => [...dl.querySelectorAll('dd')].map(d => d.textContent))")
    want = [[iv["eligibility"], "None" if iv["status"] is None else iv["status"]] for iv in ivs]
    require(pairs == want, f"{name}: eligibility and status are not the API values: {pairs} vs {want}")
    require(texts(cdp, "#kybDneList li") == body["does_not_establish"], f"{name}: global statements differ")
    require(len(body["does_not_establish"]) == 6, f"{name}: the API did not return six global statements")
    inds = body["indicators"]
    if body["interpretation"]["scope"] == "interpreted":
        require(texts(cdp, ".kyb-ind-title") == [i["label"] for i in inds], f"{name}: indicator titles differ or are concatenated")
        require(texts(cdp, ".kyb-ind-dne") == [i["does_not_establish"] for i in inds], f"{name}: indicator does_not_establish differs")
    for i in inds:
        if i["id"] in NINE:
            require(i["does_not_establish"] == NINE[i["id"]], f"{name}: the API changed the {i['id']} string")
    require(texts(cdp, "#kybAttribution") == [body["attribution"]], f"{name}: attribution differs")
    filings = body.get("registered_office_change_filings")
    if filings and filings["source_status"] == "available":
        require(texts(cdp, ".kyb-filing") == [f"{f['date']}: {f['description_identifier']}" for f in filings["items"][:20]],
                f"{name}: filings are not date plus description")
        for f in filings["items"]:
            require(f["transaction_id"] not in section_text(cdp, "kyb-h-filings"), f"{name}: transaction id is shown")
    labels = texts(cdp, "#kyb-h-company ~ dl dt")
    require("Date when the company was created" in labels, f"{name}: creation date label, got {labels}")
    require(not any(label.startswith("Incorporated") for label in labels), f"{name}: invented date label")
    charges = next((i for i in inds if i["id"] == "outstanding_charges"), None)
    if charges:
        shown = section_text(cdp, "kyb-h-charges")
        for c in charges["evidence"]["charges"]:
            require(c["created_on"] in shown and c["status"] in shown, f"{name}: charge detail missing: {c}")
    print(f"OK: contract, {name}: IDV text, eligibility, status, six global items, indicator strings, filings")


